#!/usr/bin/env node
/**
 * Bundle-leak gate (P5-5): fail the build if any internal-only string
 * escapes into the public client bundle. The public map's dist/ must look
 * exactly like a public map — no internal route fragments, feature names,
 * or dataset slugs, even in lazy-loaded chunks (they're all world-readable
 * on the CDN).
 *
 * Runs automatically after `npm run build` (postbuild hook). CI fails on
 * any match. When a canary legitimately needs to ship (it shouldn't),
 * remove it here in the same PR that adds it — reviewable in one place.
 */
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import process from 'node:process'
import { execFileSync } from 'node:child_process'

// ---------------------------------------------------------------------------
// THE CANARY LIST. One entry per internal concept; matched case-insensitively
// as a substring against every text file in dist/. Keep entries specific
// enough to avoid false positives (e.g. 'api/library' not 'library').
// ---------------------------------------------------------------------------
const CANARIES = [
  // 'api/library' retired in P5-9: the catalog browser UI ships in the client
  // (the DATA is the gate — every /api/library/* response is session-checked),
  // so the route string legitimately appears in the bundle now.
  'blo_internal_session', // session cookie name (server-side concern only)
  // 'wiki' retired in P5-15: the wiki UI ships in the client (the DATA is the
  // gate — every /api/wiki/* request is session-checked), so the route string
  // legitimately appears in the bundle now.
  // 'needs-cataloging' retired in P5-11: the upload/filing UI ships in the
  // client (the DATA is the gate — every /api/library/* request is
  // session-checked), so the queue status string legitimately appears now.
  'library_users',      // DB table names must never reach a client bundle
  'library_sessions',
  'library_audit',
  'dev-admin',          // seeded dev credentials
  'dev-password',
  'blo-library',        // object storage bucket name (P5-7) — server-side only
  'LIBRARY_BUCKET',     // bucket env-var family must never be inlined client-side
  'p518-standin',       // P5-18 stand-in internal dataset slug — layer names/slugs are server-side only
  // Content canaries (P5-19 audit): real internal subject matter. The hub
  // page slug used to be baked into the client (caught by review, not by
  // this gate) — now the gate would catch it.
  'homesteading',
]

// Text-ish files worth scanning; skip images/fonts/sourcemap-free binaries.
const TEXT_EXTENSIONS = new Set(['.js', '.mjs', '.css', '.html', '.json', '.txt', '.svg', '.webmanifest', '.map'])

// dist/datasets is the public data mirror (tens of MB of CSVs that
// legitimately mention counties, not code) — scanning it would be slow:
// internal datasets must never be placed there at all, which is a repo-layout
// rule (server-side serving), not a string-canary problem.
const SKIP_DIRS = new Set(['datasets'])

const distDir = new URL('../dist', import.meta.url).pathname

function* walkFiles(dir) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    const st = statSync(full)
    if (st.isDirectory()) {
      if (!SKIP_DIRS.has(entry)) yield* walkFiles(full)
    } else {
      const dot = entry.lastIndexOf('.')
      const ext = dot === -1 ? '' : entry.slice(dot).toLowerCase()
      if (TEXT_EXTENSIONS.has(ext)) yield full
    }
  }
}

let scanned = 0
const hits = []
try {
  for (const file of walkFiles(distDir)) {
    scanned++
    const content = readFileSync(file, 'utf8').toLowerCase()
    for (const canary of CANARIES) {
      if (content.includes(canary.toLowerCase())) {
        hits.push({ file: relative(distDir, file), canary })
      }
    }
  }
} catch (err) {
  console.error(`bundle-leak check: cannot scan ${distDir} (${err.message}). Run a build first.`)
  process.exit(1)
}

if (scanned === 0) {
  console.error('bundle-leak check: no text files found in dist/ — build output missing?')
  process.exit(1)
}

// dist/datasets is skipped by the string scan (see SKIP_DIRS), so gate it by
// provenance instead (P5-19 audit): every file there must be a git-tracked
// public dataset. An internal CSV dropped into public/datasets/ is untracked
// until someone commits it deliberately — and fails the build until then.
const datasetsDir = join(distDir, 'datasets')
let datasetFiles = []
try {
  datasetFiles = [...walkFilesUnfiltered(datasetsDir)]
} catch {
  datasetFiles = [] // no public datasets in this build — nothing to gate
}

// P5-90 exception: `datasets/build/` holds derived files — one county data
// JSON and one county geometry, both named by the hash of their own contents
// and regenerated by `scripts/build-datasets.mjs` from the tracked public
// datasets on every build. They are deliberately not committed (they would
// churn megabytes per data refresh), so git provenance cannot speak for them.
// They are gated by the generated manifest instead: the build directory may
// contain exactly the two files the manifest names, and nothing else. An
// internal file dropped in there is not in the manifest, and still fails.
const buildDirName = 'build'
const manifestedBuildFiles = new Set()
try {
  const manifest = JSON.parse(
    readFileSync(join(distDir, '..', 'src/config/datasetsManifest.generated.json'), 'utf8'),
  )
  for (const url of Object.values(manifest)) {
    const name = typeof url === 'string' ? url.split('/').pop() : ''
    // Belt and braces: the manifest is generated, but only ever names these.
    // Deliberately a copy of build-datasets.mjs's BUILT_FILE_PATTERN — a gate
    // should not import the thing it gates. Change both together.
    if (/^(?:county-data|counties)\.[0-9a-f]{10}\.(?:json|geojson)$/.test(name)) {
      manifestedBuildFiles.add(join(buildDirName, name))
    }
  }
} catch (err) {
  if (datasetFiles.some(f => relative(datasetsDir, f).startsWith(`${buildDirName}/`))) {
    console.error(
      `bundle-leak check: dist/datasets/${buildDirName} exists but the dataset manifest is unreadable (${err.message}) — refusing to pass unverified build output.`,
    )
    process.exit(1)
  }
}
datasetFiles = datasetFiles.filter(f => !manifestedBuildFiles.has(relative(datasetsDir, f)))

if (datasetFiles.length > 0) {
  let tracked
  try {
    tracked = new Set(
      execFileSync('git', ['ls-files', '-z', 'public/datasets'], { cwd: join(distDir, '..'), encoding: 'utf8' })
        .split('\0')
        .filter(Boolean)
        .map(p => p.replace(/^public\/datasets\//, '')),
    )
  } catch (err) {
    console.error(`bundle-leak check: cannot list tracked public datasets (${err.message}) — refusing to pass an unverified dist/datasets.`)
    process.exit(1)
  }
  const untracked = datasetFiles.map(f => relative(datasetsDir, f)).filter(f => !tracked.has(f))
  if (untracked.length > 0) {
    console.error('bundle-leak check FAILED — dist/datasets contains files that are not git-tracked public datasets:')
    for (const f of untracked) console.error(`  dist/datasets/${f}`)
    console.error('Internal data never goes under public/. If this file is genuinely public, commit it.')
    process.exit(1)
  }
}

function* walkFilesUnfiltered(dir) {
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith('.')) continue // .DS_Store and friends are not data
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) yield* walkFilesUnfiltered(full)
    else yield full
  }
}

if (hits.length > 0) {
  console.error('bundle-leak check FAILED — internal strings found in the public bundle:')
  for (const { file, canary } of hits) {
    console.error(`  dist/${file}: contains canary "${canary}"`)
  }
  console.error('Internal features must stay out of client code (serve via authenticated API).')
  process.exit(1)
}

console.log(`bundle-leak check passed (${scanned} files scanned, ${CANARIES.length} canaries).`)
